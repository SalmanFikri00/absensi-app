const base = process.env.BASE_URL ?? 'http://127.0.0.1:3187';
let passed = 0;
function ok(condition: unknown, message: string) {
  if (!condition) throw new Error(`FAIL: ${message}`);
  passed += 1; console.log(`PASS: ${message}`);
}
for (const route of ['/', '/user', '/admin', '/admin/users', '/admin/scan']) {
  const response = await fetch(`${base}${route}`);
  const html = await response.text();
  ok(response.ok && html.length > 500, `halaman ${route} merespons HTML`);
}
const publicWorkers = await fetch(`${base}/api/users`);
ok(publicWorkers.status === 401, 'direktori pekerja tidak dibuka untuk publik');
const protectedManagement = await fetch(`${base}/api/admin/workers`);
ok(protectedManagement.status === 401, 'manajemen akun hanya dapat diakses admin');
const beforeLogin = await fetch(`${base}/api/admin/overview`);
ok(beforeLogin.status === 401, 'dashboard API menolak sesi tanpa autentikasi');
const publicCheckIn = await fetch(`${base}/api/attendance`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ payload: '{}' }) });
ok(publicCheckIn.status === 401, 'API check-in hanya menerima sesi petugas');
const badLogin = await fetch(`${base}/api/admin/session`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ pin: '0000' }) });
ok(badLogin.status === 401, 'PIN petugas yang salah ditolak');
const login = await fetch(`${base}/api/admin/session`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ pin: '2468' }) });
const adminCookie = login.headers.get('set-cookie')?.split(';', 1)[0];
ok(login.ok && Boolean(adminCookie), 'PIN petugas demo membuat sesi HTTP-only');
const adminHeaders = { Cookie: adminCookie! };
const overview = await fetch(`${base}/api/admin/overview`, { headers: adminHeaders });
ok(overview.ok, 'dashboard dapat diakses setelah login');
const directory = await fetch(`${base}/api/admin/workers`, { headers: adminHeaders });
const directoryData = await directory.json() as { workers: Array<{ id: string }> };
ok(directory.ok && directoryData.workers.length === 10, 'panel admin dapat melihat 10 akun seed');
const wrongPin = await fetch(`${base}/api/profile`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id: 'EMP-001', pin: '0000' }) });
ok(wrongPin.status === 401, 'PIN pekerja yang salah ditolak');
const profileResponse = await fetch(`${base}/api/profile`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id: 'EMP-001', pin: '1234' }) });
const workerCookie = profileResponse.headers.get('set-cookie')?.split(';', 1)[0];
const profile = await profileResponse.json() as { qr: string; attendance: { checkedIn: boolean } };
ok(profileResponse.ok && Boolean(workerCookie) && profile.qr.startsWith('{') && !profile.attendance.checkedIn, 'ID dan PIN pekerja membuka QR serta sesi HTTP-only');
const restored = await fetch(`${base}/api/profile`, { headers: { Cookie: workerCookie! } });
const restoredData = await restored.json() as { worker: { id: string } };
ok(restored.ok && restoredData.worker.id === 'EMP-001', 'sesi pekerja pulih setelah halaman dimuat ulang');
const headers = { 'Content-Type': 'application/json', Cookie: adminCookie! };
const checkIn = await fetch(`${base}/api/attendance`, { method: 'POST', headers, body: JSON.stringify({ payload: profile.qr }) });
const checkInData = await checkIn.json() as { status: string; worker?: { id: string } };
ok(checkIn.status === 201 && checkInData.status === 'success' && checkInData.worker?.id === 'EMP-001', 'QR valid menyimpan check-in');
const duplicate = await fetch(`${base}/api/attendance`, { method: 'POST', headers, body: JSON.stringify({ payload: profile.qr }) });
const duplicateData = await duplicate.json() as { status: string };
ok(duplicate.status === 409 && duplicateData.status === 'duplicate', 'scan ulang ditolak sebagai duplikasi');
const badQr = await fetch(`${base}/api/attendance`, { method: 'POST', headers, body: JSON.stringify({ payload: JSON.stringify({ uid: 'EMP-001', t: Math.floor(Date.now() / 1000), sig: '0'.repeat(64) }) }) });
ok(badQr.status === 400, 'QR dengan tanda tangan palsu ditolak');
const afterProfile = await fetch(`${base}/api/profile`, { headers: { Cookie: workerCookie! } });
const afterData = await afterProfile.json() as { attendance: { checkedIn: boolean } };
ok(afterData.attendance.checkedIn, 'portal pekerja memperlihatkan status hadir setelah scan');
const afterOverview = await fetch(`${base}/api/admin/overview`, { headers: adminHeaders });
const overviewData = await afterOverview.json() as { present: number; pending: number; recent: Array<{ user_id: string }> };
ok(overviewData.present === 1 && overviewData.pending === 1 && overviewData.recent[0]?.user_id === 'EMP-001', 'dashboard menghitung hadir, antrean, dan log terbaru dengan benar');
const logout = await fetch(`${base}/api/profile`, { method: 'DELETE', headers: { Cookie: workerCookie! } });
const loggedOutSession = await fetch(`${base}/api/profile`, { headers: { Cookie: workerCookie! } });
ok(logout.ok && loggedOutSession.status === 401, 'logout mencabut token sesi pekerja di server');
const created = await fetch(`${base}/api/admin/workers`, { method: 'POST', headers, body: JSON.stringify({ id: 'EMP-TEST-1', name: 'Pekerja Tes', division: 'Operasional', pin: '9876' }) });
const createdData = await created.json() as { worker?: { id: string } };
ok(created.status === 201 && createdData.worker?.id === 'EMP-TEST-1', 'admin dapat membuat akun pekerja baru');
const duplicateId = await fetch(`${base}/api/admin/workers`, { method: 'POST', headers, body: JSON.stringify({ id: 'EMP-TEST-1', name: 'Duplikat', division: 'Operasional', pin: '1234' }) });
ok(duplicateId.status === 409, 'ID pekerja duplikat ditolak');
const firstCreatedLogin = await fetch(`${base}/api/profile`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id: 'EMP-TEST-1', pin: '9876' }) });
const firstCreatedCookie = firstCreatedLogin.headers.get('set-cookie')?.split(';', 1)[0];
const editAccount = await fetch(`${base}/api/admin/workers`, { method: 'PATCH', headers, body: JSON.stringify({ id: 'EMP-TEST-1', name: 'Pekerja Tes', division: 'Lapangan', active: true, pin: '1122' }) });
ok(editAccount.ok, 'admin dapat mengubah divisi dan mereset PIN');
const oldSessionAfterReset = await fetch(`${base}/api/profile`, { headers: { Cookie: firstCreatedCookie! } });
ok(firstCreatedLogin.ok && oldSessionAfterReset.status === 401, 'reset PIN mencabut sesi yang sudah login');
const newPinLogin = await fetch(`${base}/api/profile`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id: 'EMP-TEST-1', pin: '1122' }) });
ok(newPinLogin.ok, 'PIN yang direset dapat digunakan untuk login');
const newPinCookie = newPinLogin.headers.get('set-cookie')?.split(';', 1)[0];
const disabled = await fetch(`${base}/api/admin/workers`, { method: 'PATCH', headers, body: JSON.stringify({ id: 'EMP-TEST-1', name: 'Pekerja Tes', division: 'Lapangan', active: false }) });
const disabledLogin = await fetch(`${base}/api/profile`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id: 'EMP-TEST-1', pin: '1122' }) });
ok(disabled.ok && disabledLogin.status === 401, 'akun nonaktif tidak dapat masuk');
const disabledSession = await fetch(`${base}/api/profile`, { headers: { Cookie: newPinCookie! } });
ok(disabledSession.status === 401, 'penonaktifan akun mencabut sesi yang sudah login');
const reactivated = await fetch(`${base}/api/admin/workers`, { method: 'PATCH', headers, body: JSON.stringify({ id: 'EMP-TEST-1', name: 'Pekerja Tes', division: 'Lapangan', active: true }) });
const revivedOldSession = await fetch(`${base}/api/profile`, { headers: { Cookie: newPinCookie! } });
ok(reactivated.ok && revivedOldSession.status === 401, 'aktivasi ulang tidak menghidupkan kembali token lama');
console.log(`\n${passed} smoke checks passed.`);
export {};
